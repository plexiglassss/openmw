"""Bind installed shared-profile resources to executed native lifecycle tests.

The shared YAML is user configuration generated by Lumenaire. The distribution
must not install a live rule, or resume discovery of retired per-mod profiles.
"""
import base64
import hashlib
import json
from pathlib import Path
import sys
from xml.etree import ElementTree

repo = Path(__file__).resolve().parents[3]
install = Path(sys.argv[1])
vfs = install / 'resources/vfs'


def require(value, message):
    if not value:
        raise ValueError(message)


def cases(path, suite_name):
    tree = ElementTree.parse(path)
    result = {c.get('name'): c for c in tree.iter('testcase') if c.get('classname') == suite_name}
    require(result and all(c.get('status') == 'run' and c.get('result') == 'completed'
                           and all(c.find(tag) is None for tag in ('failure', 'error', 'skipped'))
                           for c in result.values()),
            f'Missing or incomplete {suite_name} in {path}')
    return result


require(not (vfs / 'shader_profiles').exists(), 'Retired per-mod profile resources were bundled again')
require(not list((repo / 'files/data/shader_profiles').glob('*')), 'Retired per-mod source profiles remain')
require(not list(install.rglob('location-rendering.yaml')),
        'The distribution must not ship a live user shared configuration')
engine = (repo / 'apps/openmw/engine.cpp').read_text(encoding='utf-8')
require('mCfgMgr.getUserConfigPath() / "location-rendering.yaml"' in engine,
        'The shared file is not rooted in the active user configuration directory')
reader = (repo / 'apps/openmw/mwrender/locationrenderingprofiles.cpp').read_text(encoding='utf-8')
require('VFS::' not in reader and 'shader_profiles/' not in reader,
        'The profile reader regained per-mod resource discovery')

layout = ElementTree.parse(vfs / 'mygui/openmw_settings_window.layout')
require(any({entry.get('key'): entry.get('value') for entry in widget.findall('UserString')}.items()
            >= {'SettingName': 'location rendering profiles', 'SettingCategory': 'Shaders', 'SettingType': 'CheckButton'}.items()
            for widget in layout.iter('Widget')), 'The Lights option is missing')
require(b'location rendering profiles = true' in base64.b64decode((install / 'defaults.bin').read_bytes()),
        'The compiled default is missing')
shaders = ('lib/light/locationrenderingprofile.glsl', 'lib/light/clamp.glsl', 'lib/light/objectlighting.glsl',
           'compatibility/objects.vert', 'compatibility/objects.frag', 'compatibility/bs/default.vert', 'compatibility/bs/default.frag')
shader_hashes = {}
for shader in shaders:
    data = (install / 'resources/shaders' / shader).read_bytes()
    require(data == (repo / 'files/shaders' / shader).read_bytes(), shader)
    shader_hashes[shader] = hashlib.sha256(data).hexdigest()

required = {
    'LocationRenderingProfileTest': {
        'parsesAllFourShaderValues',
        'parsesGenericConditionWithoutAnyModOrCellList',
        'matchesExactInteriorOnlyWhenAllRequiredContentIsActive',
        'loadsOnlySharedFileAndDoesNotFallBackToLegacyProfiles',
        'invalidRuleDoesNotDisableOtherValidRules',
        'badDocumentNeverUsesPreviouslyLoadedOrLegacyProfiles',
        'duplicateIdsInSharedFileRejectAllOccurrences',
        'disabledProfileDoesNotPublishAnyMatch',
        'explicitHigherPriorityWinsOverAutomaticConditionInEitherOrder',
        'conflictingPriorityUsesGlobalsOnlyInAffectedMatches',
        'identicalEqualPriorityMatchesAreDeterministic',
        'conditionConflictDoesNotAffectLocationsWithoutNegativeLight',
        'rejectsUnknownAndAmbiguousMatchForms',
        'requiresCompleteShaderValuesAndValidIdentifiers',
        'wildcardLookingCellNamesRemainLiteral',
        'qualifyingColourIgnoresAlphaRadiusAndAnimationFlags',
        'trackerOnlyNotifiesZeroCrossingsAndMovesAtomically',
        'trackerAndConditionalProfileRestoreOrdinaryUniforms',
        'stateUpdaterPublishesProfileAndOrdinaryMapUniforms',
    },
    'NegativeLightLifecycleTest': {
        'PlacedSourcesRemainUntilTheLastRemoval',
        'ActiveMoveTransfersMembershipBeforeOldCellUnload',
        'OffDefaultAndBlackRecordsDoNotActivateButZeroRadiusDoes',
        'DisableReenableAndClearedWorldRebuildMembership',
        'InventoryReferenceAndPreviewCannotActivateTheWorld',
        'EquippedAndAdditionalSourcesFollowActualAttachment',
        'FlickerPulseFadeAndCameraMasksDoNotToggleMembership',
    },
}
executed = {}
for suite, expected in required.items():
    packaged = cases('location-rendering-profile-tests.xml', suite)
    require(expected <= packaged.keys(), f'Missing mandatory shared-profile cases in {suite}')
    require(packaged.keys() == cases('openmw-tests.xml', suite).keys(),
            f'Source and package-phase {suite} cases differ')
    executed[suite] = sorted(packaged)
require('get_program_with_null_vertex_shader_does_not_dereference' in cases('components-tests.xml', 'ShaderManagerTest'),
        'Missing shader program regression')

result = dict(result='PASS', format=3, shared_file='active-user-config/location-rendering.yaml',
              bundled_profiles=0, legacy_discovery=False, default_enabled=True,
              native_test_suites=executed, shaders_sha256=shader_hashes,
              live_gameplay_tested=False)
out = install / 'verification/location-rendering-profile.json'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
print(f'Verified shared-only profile resources and {sum(map(len, executed.values()))} executed native cases.')
