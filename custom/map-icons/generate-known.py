#!/usr/bin/env python3
"""Generate the native marker index from position-free location/type facts."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FACTS = Path(__file__).with_name('known-locations.tsv')
OUTPUT = ROOT / 'components/mapmarkers/knownlocations.inc'
CATEGORIES = ('City', 'Town', 'Settlement', 'House', 'Cave', 'Mine', 'Tomb', 'Barrow',
              'Dwemer', 'Daedric', 'Stronghold', 'Fort', 'Tower', 'Ruin', 'Camp', 'Ship',
              'Shipwreck', 'Landmark', 'Misc')


def read_facts(path=FACTS):
    facts = {}
    for number, line in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
        if not line or line.startswith('#'):
            continue
        try:
            name, category = line.split('\t')
        except ValueError as error:
            raise ValueError(f'{path}:{number}: expected name and category') from error
        if not name.isascii() or name != ' '.join(name.lower().split()) or '\x00' in name:
            raise ValueError(f'{path}:{number}: name is not normalized ASCII')
        if name in facts or not name:
            raise ValueError(f'{path}:{number}: duplicate or empty name')
        if category not in {category.lower() for category in CATEGORIES}:
            raise ValueError(f'{path}:{number}: unsupported category {category!r}')
        if len(name.encode('utf-8')) > 65535:
            raise ValueError(f'{path}:{number}: name exceeds index length field')
        facts[name] = category
    if not facts:
        raise ValueError('The location catalogue is empty')
    return facts


def generate(path=FACTS):
    facts = read_facts(path)
    # Git may check out text as CRLF on Windows. Hash the normalized factual
    # text so the same catalogue generates byte-identical C++ on either OS.
    digest = hashlib.sha256(path.read_text(encoding='utf-8').encode('utf-8')).hexdigest()
    enum = {category.lower(): category for category in CATEGORIES}
    strings, rows = [], []
    offset = 0
    for name, category in sorted(facts.items()):
        escaped = name.replace('\\', '\\\\').replace('"', '\\"')
        strings.append(f'            "{escaped}\\0"')
        rows.append(f'            {{ {offset}, {len(name)}, Category::{enum[category]} }},')
        offset += len(name) + 1
    if offset >= 2**32:
        raise ValueError('The location catalogue exceeds the index offset field')
    return (
        '// Generated by custom/map-icons/generate-known.py; do not edit.\n'
        '// Location/type facts: Improved Global Map Markers 1.7, Gerotaritor.\n'
        '// Contains no source code, coordinates, or discovery state from that mod.\n'
        f'// Input SHA256 (LF-normalized): {digest}\n'
        '        constexpr char sKnownNamePool[] =\n'
        + '\n'.join(strings) + ';\n\n'
        + f'        constexpr std::array<KnownEntry, {len(rows)}> sKnownNames{{ {{\n'
        + '\n'.join(rows) + '\n        } };\n'
        + f'        static_assert(sizeof(sKnownNamePool) == {offset + 1});\n'
        + '        static_assert(sizeof(KnownEntry) == 8);\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the checked-in output differs')
    parser.add_argument('--source', type=Path, default=FACTS)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    generated = generate(args.source)
    if args.check:
        if args.output.read_text(encoding='utf-8') != generated:
            raise SystemExit('Native map marker index is out of date')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(generated, encoding='utf-8', newline='\n')
    print(f'{len(read_facts(args.source))} location names: ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
